//! One entry per element type the loader accepts.
//!
//! Split from `support.rs` so neither file has to hold the whole list: the table is
//! data, the lookups are code, and the rule that a type is supported only when it is
//! here lives with the list.

use super::TypeSupport;
use crate::element::Kind;
use crate::property;

macro_rules! type_support {
    ($kind:expr, $($property:expr),* $(,)?) => {
        TypeSupport {
            kind: $kind,
            properties: &[$($property),*],
        }
    };
}


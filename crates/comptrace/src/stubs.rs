//! The `stubs` subcommand: a Rust module that answers every export of a PE image.
//!
//! The list is the PE export table, not a hand-written one, so a new SDK version either
//! matches the committed module or `--check` reports the drift.

use std::collections::BTreeSet;
use std::fmt::Write as _;
use std::path::Path;

use crate::pe;

/// Render one stub per export, minus the names in `skip`.
pub fn render(image: &Path, skip: &[String]) -> Result<String, String> {
    let exports = pe::exports(image)?;
    let name = image.file_name().map_or_else(
        || image.display().to_string(),
        |name| name.to_string_lossy().into_owned(),
    );
    Ok(render_exports(&name, &exports, skip))
}

fn render_exports(name: &str, exports: &[pe::Export], skip: &[String]) -> String {
    let skipped: BTreeSet<&str> = skip.iter().map(String::as_str).collect();
    let total = exports.len();
    let kept = exports
        .iter()
        .filter(|export| !skipped.contains(export.name.as_str()))
        .count();

    let mut out = String::new();
    let _ = writeln!(out, "//! Stubs for the exports of `{name}`.");
    let _ = writeln!(out, "//!");
    let _ = writeln!(
        out,
        "//! Generated by `comptrace stubs` from the PE export table: {total} exports, {kept} kept."
    );
    let _ = writeln!(
        out,
        "//! A stub takes no parameters on purpose; on x86-64 the caller's arguments stay in"
    );
    let _ = writeln!(
        out,
        "//! registers and are ignored, and the HRESULT is what a caller checks."
    );
    if !skipped.is_empty() {
        let names: Vec<&str> = skipped.iter().copied().collect();
        let _ = writeln!(out, "//!");
        let _ = writeln!(out, "//! Skipped: {}", names.join(", "));
    }
    let _ = writeln!(out);
    let _ = writeln!(out, "use crate::E_NOTIMPL;");
    let _ = writeln!(out);

    for export in exports {
        if skipped.contains(export.name.as_str()) {
            continue;
        }
        let _ = writeln!(out, "#[unsafe(no_mangle)]");
        let _ = writeln!(out, "pub extern \"system\" fn {}() -> i32 {{", export.name);
        let _ = writeln!(out, "    E_NOTIMPL");
        let _ = writeln!(out, "}}");
        let _ = writeln!(out);
    }
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn exports() -> Vec<pe::Export> {
        vec![
            pe::Export {
                name: "BackButtonIntegration_RegisterListener".to_string(),
                address: 0,
            },
            pe::Export {
                name: "Containment_GetChangeEnabled".to_string(),
                address: 0,
            },
            pe::Export {
                name: "Windowing_GetWindowIdFromWindow".to_string(),
                address: 0,
            },
        ]
    }

    #[test]
    fn every_kept_export_gets_one_stub() {
        let out = render_exports("test.dll", &exports(), &[]);
        assert_eq!(out.matches("#[unsafe(no_mangle)]").count(), 3);
        assert!(out.contains("fn Containment_GetChangeEnabled() -> i32"));
        assert!(out.contains("3 exports, 3 kept"));
    }

    #[test]
    fn a_skipped_name_is_absent_and_listed() {
        let out = render_exports(
            "test.dll",
            &exports(),
            &["Containment_GetChangeEnabled".to_string()],
        );
        assert_eq!(out.matches("#[unsafe(no_mangle)]").count(), 2);
        assert!(!out.contains("fn Containment_GetChangeEnabled"));
        assert!(out.contains("Skipped: Containment_GetChangeEnabled"));
    }
}
